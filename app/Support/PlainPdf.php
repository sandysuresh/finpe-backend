        $ops = [];

        self::fill($ops, 0.114, 0.306, 0.847, 0, 760, 595, 82);
        self::fill($ops, 0.075, 0.220, 0.690, 0, 760, 595, 4);
        self::fill($ops, 1, 1, 1, 36, 782, 34, 34);
        self::text($ops, 'FP', 42, 793, 12, true, [0.114, 0.306, 0.847]);
        self::text($ops, 'FinPe', 82, 800, 20, true, [1, 1, 1]);
        self::text($ops, 'Admin Gateway', 82, 784, 9, false, [0.82, 0.89, 1]);

        self::text($ops, 'AePS Transaction Receipt', 36, 728, 16, true, [0.09, 0.14, 0.22]);
        self::drawBadge($ops, $badge[0], 430, 720, 130, 24, $badge[1], $badge[2]);

        self::card($ops, 36, 648, 252, 58);
        self::text($ops, 'AMOUNT', 48, 684, 8, true, [0.39, 0.45, 0.55]);
        self::text($ops, $receipt['amount'], 48, 662, 16, true, [0.09, 0.14, 0.22]);

        self::card($ops, 304, 648, 255, 58);
        self::text($ops, 'FINPE REFERENCE', 316, 684, 8, true, [0.39, 0.45, 0.55]);
        self::text($ops, $receipt['reference'], 316, 662, 12, true, [0.114, 0.306, 0.847]);

        $y = 628;
        $y = self::section($ops, $y, 'Transaction Details', [
            ['Service', $receipt['service']],
            ['FinPe reference', $receipt['reference']],
            ['Aadhaar', $receipt['aadhaar']],
            ['Status', $receipt['status']],
            ['Date/time', $receipt['datetime']],
        ]);
        $y = self::section($ops, $y, 'Merchant & Vendor Details', [
            ['Vendor', $receipt['vendor']],
            ['Merchant', $receipt['merchant']],
        ]);
        self::section($ops, $y, 'Provider Details', [
            ['Provider reference', $receipt['provider_reference'], true],
            ['RRN', $receipt['rrn'], true],
            ['Provider status', $receipt['provider_status']],
            ['Provider message', $receipt['provider_message']],
        ]);

        self::stroke($ops, 0.82, 0.86, 0.90, 36, 48, 523);
        self::text($ops, 'Generated by FinPe', 36, 30, 9, false, [0.39, 0.45, 0.55]);

        return self::document(implode("\n", $ops));
    }

